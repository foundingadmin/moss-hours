for (const [name, data] of [['2026-typical', typical], ['2026-edge', edge]]) {
  const path = new URL(`fixtures/${name}.json`, `file://${ROOT}`);
  await writeFile(path, JSON.stringify(data, null, 2) + '\n', 'utf8');
  console.log(
    `${name}: ${data.totals.total}h total ` +
    `(${data.totals.hours.logged} logged, ${data.totals.reconstructed} reconstructed)`
  );
}
