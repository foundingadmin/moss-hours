/**
 * Builds fixtures/*.json from the compact specs below.
 *
 *   node scripts/build-fixtures.mjs
 *
 * The fixtures are the API contract written down, and the contract now includes
 * arithmetic: a month's hours are the sum of the rounded items listed under it,
 * and its total is the sum of its three classes. Hand-maintaining that across
 * two files was a standing invitation to commit a fixture whose drawer
 * disagreed with its own row, which is the exact defect the report is supposed
 * to make impossible.
 *
 * So the specs carry per-task splits only, and every total here is derived the
 * same way api/time.js derives it. Edit a spec, rerun this, commit both.
 */
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const round = (n) => Math.round(n * 100) / 100;

/* [logged, documented, estimated] for one task, matching the three classes the
   API emits. A task can carry more than one, which is the case the report
   exists to show: one piece of work partly watched and partly rebuilt. */
const task = (id, name, [l, d, e], extra = {}) => {
  const hours = { logged: round(l), documented: round(d), estimated: round(e) };
  return {
    id,
    name,
    url: extra.url === null ? null : `https://app.clickup.com/t/${id}`,
    hours,
    reconstructed: round(hours.documented + hours.estimated),
    total: round(hours.logged + hours.documented + hours.estimated),
    ...(extra.aggregated ? { count: extra.count, aggregated: true, id: null, url: null } : {}),
  };
};

const sum = (items) => {
  const hours = items.reduce(
    (a, t) => ({
      logged: a.logged + t.hours.logged,
      documented: a.documented + t.hours.documented,
      estimated: a.estimated + t.hours.estimated,
    }),
    { logged: 0, documented: 0, estimated: 0 }
  );
  const h = { logged: round(hours.logged), documented: round(hours.documented), estimated: round(hours.estimated) };
  return {
    hours: h,
    reconstructed: round(h.documented + h.estimated),
    total: round(h.logged + h.documented + h.estimated),
  };
};

const build = (meta, monthSpecs) => {
  const months = Array.from({ length: 12 }, (_, i) => {
    const items = monthSpecs[i] || [];
    return { month: i, ...sum(items), items };
  });
  const totals = sum(months.map((m) => ({ hours: m.hours })));
  return { ...meta, months, totals };
};

